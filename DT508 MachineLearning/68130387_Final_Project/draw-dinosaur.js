/**
 * @param {CanvasRenderingContext2D} context
 * @param {object} dinosaur
 * @param {object} options
 */
export function drawDinosaur(
  context,
  dinosaur,
  options = {},
) {
  if (!context || !dinosaur) {
    return;
  }

  const {
    pixelSize = 5,
    bodyColor = "#555555",
  } = options;

  const frame = getDinosaurFrame(dinosaur);

  if (!frame) {
    return;
  }

  const spriteWidth =
    getFrameWidth(frame) * pixelSize;

  const spriteHeight =
    frame.length * pixelSize;

  /*
    ใช้ขนาด Sprite จริงจัดกึ่งกลางกับ Hitbox
  */
  const drawX = Math.round(
    dinosaur.x +
      (dinosaur.width - spriteWidth) / 2,
  );

  /*
    ทุกเฟรมมีความสูง 14 ช่องเท่ากัน
    จึงจัดด้านล่างให้ตรงกับตำแหน่งเท้า
  */
  const drawY = Math.round(
    dinosaur.y +
      dinosaur.height -
      spriteHeight,
  );

  context.save();
  context.imageSmoothingEnabled = false;

  drawPixelSprite(
    context,
    frame,
    drawX,
    drawY,
    pixelSize,
    bodyColor,
  );

  context.restore();
}

/* =========================================================
   เลือกเฟรมตามสถานะ
========================================================= */

function getDinosaurFrame(dinosaur) {
  /*
    ลำดับสำคัญ:
    Dead ต้องตรวจเป็นอันดับแรก
  */
  if (dinosaur.isDead) {
    return DINO_FRAMES.dead;
  }

  /*
    กระโดดใช้เฟรม stand ค้าง
    ไม่สลับขาระหว่างอยู่กลางอากาศ
  */
  if (dinosaur.isJumping) {
    return DINO_FRAMES.stand;
  }

  /*
    ย่อตัววิ่งสลับ crouch1 และ crouch2
  */
  if (dinosaur.isCrouching) {
    return dinosaur.crouchFrame === 0
      ? DINO_FRAMES.crouch1
      : DINO_FRAMES.crouch2;
  }

  /*
    วิ่งปกติสลับ run1 และ run2
  */
  return dinosaur.runFrame === 0
    ? DINO_FRAMES.run1
    : DINO_FRAMES.run2;
}

/* =========================================================
   วาด Pixel
========================================================= */

function drawPixelSprite(
  context,
  frame,
  startX,
  startY,
  pixelSize,
  color,
) {
  context.fillStyle = color;

  for (
    let row = 0;
    row < frame.length;
    row += 1
  ) {
    const rowData = frame[row];

    for (
      let column = 0;
      column < rowData.length;
      column += 1
    ) {
      if (rowData[column] !== "1") {
        continue;
      }

      context.fillRect(
        startX + column * pixelSize,
        startY + row * pixelSize,
        pixelSize,
        pixelSize,
      );
    }
  }
}

/* =========================================================
   Helper
========================================================= */

function getFrameWidth(frame) {
  return frame.reduce(
    (maximumWidth, row) =>
      Math.max(
        maximumWidth,
        row.length,
      ),
    0,
  );
}